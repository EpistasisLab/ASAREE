export const RECOMMENDED_METRIC_KEYS = METRIC_CATALOG.filter((entry) => entry.recommended).map((entry) => entry.key)

export function metricCatalogEntry(key: string | undefined): MetricCatalogEntry | undefined {
  return METRIC_CATALOG.find((entry) => entry.key === key)
}

function legacyId(metric: Partial<DesignMetric>): string {
  // Deterministic for old, read-only records; an edited/saved declaration is
  // normalized at the API boundary with the same stable value.
  const text = `${metric.catalogKey ?? ''}:${(metric.name ?? 'metric').toLocaleLowerCase()}:${metric.kind ?? 'custom'}:${metric.valueType ?? 'number'}:${metric.direction ?? 'maximize'}`
  let hash = 2166136261
  for (const char of text) hash = Math.imul(hash ^ char.charCodeAt(0), 16777619)
  return `legacy-metric-${(hash >>> 0).toString(36)}`
}

/** Preserve unknown persisted fields while making pre-catalog metrics usable. */
export function normalizeDesignMetrics(metrics: DesignMetric[] | undefined): DesignMetric[] {
  const source = Array.isArray(metrics) ? metrics : []
  return source.flatMap((raw) => {
    if (!raw || typeof raw.name !== 'string' || !raw.name.trim()) return []
    const catalog = metricCatalogEntry(raw.catalogKey)
    if (raw.kind && !['runtime', 'custom'].includes(raw.kind)) return []
    return [{
      ...raw,
      id: typeof raw.id === 'string' && raw.id ? raw.id : legacyId(raw),
      catalogKey: catalog ? catalog.key : raw.catalogKey,
      name: raw.name.trim(),
      description: typeof raw.description === 'string' && raw.description.trim()
        ? raw.description.trim()
        : catalog?.shortDescription ?? `Legacy metric declaration for ${raw.name.trim()}.`,
      kind: raw.kind ?? catalog?.kind ?? 'custom',
      valueType: (raw.kind ?? catalog?.kind) === 'custom' ? 'opaque' : raw.valueType ?? catalog?.valueType ?? 'number',
      direction: (raw.kind ?? catalog?.kind) === 'custom' ? 'neutral' : raw.direction === 'maximize' || raw.direction === 'minimize' || raw.direction === 'neutral'
        ? raw.direction
        : (catalog?.defaultDirection ?? 'maximize'),
      aggregation: (raw.kind ?? catalog?.kind) === 'custom' ? 'none' : raw.valueType === 'boolean' ? 'mean' : (raw.aggregation === 'sum' ? 'sum' : (catalog?.aggregation ?? 'mean')),
      primary: (raw.kind ?? catalog?.kind) === 'custom' ? false : Boolean(raw.primary),
      unit: raw.unit ?? catalog?.unit,
      scoring: undefined,
    }]
  })
}

export function makeCatalogMetric(entry: MetricCatalogEntry, isPrimary: boolean): DesignMetric {
  return {
    id: newMetricId(),
    catalogKey: entry.key,
    name: entry.name,
    description: entry.shortDescription,
    kind: entry.kind,
    valueType: entry.valueType,
    direction: entry.defaultDirection,
    aggregation: entry.aggregation ?? 'mean',
    primary: isPrimary,
    unit: entry.unit,
  }
}

export function makeCustomMetric(input: { name: string; description: string; unit?: string }): DesignMetric {
  return {
    id: newMetricId(),
    name: input.name.trim(),
    description: input.description.trim(),
    kind: 'custom',
    valueType: 'opaque',
    direction: 'neutral',
    aggregation: 'none',
    primary: false,
    unit: input.unit?.trim() || undefined,
  }
}

// Metric IDs have the same browser requirement as canvas IDs: they must work
// in plain-HTTP development deployments as well as HTTPS, where
// crypto.randomUUID() is unavailable.
function newMetricId(): string {
  return newNodeId().replace(/^node-/, 'metric-')
}
