/**
 * The only client-side catalog of metric definitions.  A metric declaration
 * stores a snapshot of this metadata so an experiment remains intelligible if
 * the catalog changes later; the catalog is never a promise that an Agent can
 * calculate the metric itself.
 */
export type MetricKind = 'runtime' | 'custom'
export type MetricValueType = 'number' | 'boolean' | 'string' | 'opaque'
export type MetricDirection = 'maximize' | 'minimize' | 'neutral'
export type MetricAggregation = 'mean' | 'sum' | 'none'
export type MetricCategory = 'Efficiency' | 'Tokens' | 'Tools' | 'Agents' | 'Critics'
export type MetricSource = 'Run summary' | 'Protocol activity'

export interface MetricCatalogEntry {
  key: string
  name: string
  shortDescription: string
  kind: MetricKind
  valueType: MetricValueType
  defaultDirection: MetricDirection
  aggregation?: MetricAggregation
  unit?: string
  category: MetricCategory
  source: MetricSource
  recommended?: boolean
}

