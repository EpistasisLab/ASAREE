"""Generate clearly labeled synthetic reports through the production statistics path.

Run with the project environment: python scripts/stats_example.py <output-directory>
No database, model calls, or credentials are required.
"""

from __future__ import annotations

import hashlib
import json
import sys
from datetime import UTC, datetime
from html import escape
from pathlib import Path

import numpy as np

from asaree.services.stats_html import render_html
from asaree.services.stats_prototypes import StatsRequest, compute


def main():
    destination = Path(sys.argv[1])
    destination.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(20261022)
    rows = []
    for i in range(240):
        treatment = i % 2
        context = (i // 2) % 2
        rows.append(
            dict(
                id=f"demo-{i}",
                replicate=i // 4 + 1,
                factors={
                    "Approach": "Standard" if treatment == 0 else "Revised",
                    "Setting": "Basic" if context == 0 else "Extended",
                },
                metrics={
                    "Duration": float(rng.gamma(5, (10 - 2 * treatment + 0.5 * context) / 5)),
                    "Calls": int(rng.poisson(4 - treatment)),
                    "Success": "yes" if rng.random() < 0.45 + 0.2 * treatment else "no",
                    "Rating": str(rng.choice(["low", "medium", "high"], p=[0.2, 0.5, 0.3])),
                    "Explanation": "The run completed with a detailed explanation.",
                },
            )
        )
    source = dict(
        rows=rows,
        design_revision=1,
        design_revision_id="synthetic-demo",
        excluded_row_replicates=0,
        demo=True,
        metric_metadata={
            "Duration": dict(
                kind="runtime",
                unit="seconds",
                direction="minimize",
                description="Elapsed time for one run, measured in seconds.",
            ),
            "Calls": dict(
                kind="runtime",
                unit="calls",
                direction="minimize",
                description="Number of tool-call attempts in one run.",
            ),
            "Success": dict(
                kind="custom",
                description="Example yes/no success flag; this synthetic demo "
                "does not define a real success criterion.",
            ),
            "Rating": dict(
                kind="custom", description="Example qualitative assessment of a run, ordered low, medium, high."
            ),
            "Explanation": dict(
                kind="custom",
                value_type="opaque",
                description="Free-text explanation produced by a run, rather than a numeric measurement.",
            ),
        },
    )
    source["fingerprint"] = hashlib.sha256(json.dumps(source, sort_keys=True).encode()).hexdigest()
    links = []
    for index, metric in enumerate(source["metric_metadata"]):
        config = StatsRequest(metric=metric).model_dump(mode="json")
        output = compute("stats_sm", source, config)
        analysis = dict(id=f"synthetic-demo-{index}", created_at=datetime.now(UTC).isoformat(), output=output)
        filename = f"statistics-{metric.lower()}-example.html"
        (destination / filename).write_text(render_html(analysis))
        description = output["summary"]["metric_info"]["description"]
        links.append(
            f'<li><a href="{filename}">{escape(metric)}</a> — {output["summary"]["status"]}'
            f'<p style="font-size:16px;margin:0 0 16px">{escape(description)}</p></li>'
        )
        print(f"{metric}: {output['family']} / {output['validity']}")
    index_html = (
        '<!doctype html><html lang="en"><meta charset="utf-8"><title>ASAREE statistics examples</title>'
        '<body style="font:18px/1.6 system-ui;max-width:900px;margin:40px auto;padding:24px">'
        "<h1>ASAREE statistics examples</h1><p>DEMONSTRATION: synthetic data, not a real experiment. "
        "Each report was generated by the automatic analysis and HTML export code.</p><ul>"
        + "".join(links)
        + "</ul></body></html>"
    )
    (destination / "statistics-example.html").write_text(index_html)


if __name__ == "__main__":
    main()
